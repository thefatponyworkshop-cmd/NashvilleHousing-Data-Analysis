--• Assignment 15: Find properties that sold for less than their total assessed TotalValue, 
--calculating the exact discount percentage, to create a "Bargain List" for investors.

  SELECT 
    UniqueID, ParcelID, PropertyAddress, SalePrice, TotalValue,
    (TotalValue - SalePrice) AS DiscountAmount,
    CAST(((TotalValue - SalePrice) * 100.0 / TotalValue) AS DECIMAL(10,2)) AS DiscountPercentage
FROM [dbo].[NashvilleHousingEstate]
WHERE SalePrice < TotalValue AND TotalValue > 0
ORDER BY DiscountPercentage DESC;


