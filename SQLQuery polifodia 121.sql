--• Assignment 18: Identify "Fixer-Uppers" by filtering for properties built before 1970 that have a building value significantly lower 
--than the land value itself.

 SELECT 
    UniqueID, PropertyAddress, YearBuilt, LandValue, BuildingValue, TotalValue, SalePrice
FROM [dbo].[NashvilleHousingEstate]
WHERE YearBuilt < 1970 
  AND BuildingValue < (0.5 * LandValue) 
  AND BuildingValue > 0
ORDER BY YearBuilt ASC;


--• Assignment 19: Find the top 10 most prominent property owners (OwnerName) by total acreage owned in the Nashville area, 
--excluding institutional or government entities if possible.

 SELECT TOP 10
    OwnerName,
    COUNT(*) AS PropertiesOwned,
    SUM(Acreage) AS TotalCombinedAcreage,
    SUM(CAST(TotalValue AS BIGINT)) AS AssetPortfolioWorth
FROM [dbo].[NashvilleHousingEstate]
WHERE OwnerName IS NOT NULL 
  AND OwnerName NOT LIKE '%CITY OF%' 
  AND OwnerName NOT LIKE '%METROPOLITAN GOVERNMENT%'
GROUP BY OwnerName
ORDER BY TotalCombinedAcreage DESC;


--• Assignment 20: Create an investment score using a CASE WHEN statement that flags properties as "High Priority Buy" 
--if they are underpriced, located in a high-growth tax district, and have at least 3 bedrooms.

  SELECT 
    UniqueID, PropertyAddress, SalePrice, TotalValue, Bedrooms, TaxDistrict,
    CASE 
        WHEN SalePrice < (TotalValue * 0.85) AND Bedrooms >= 3 AND TaxDistrict LIKE '%URBAN%' THEN 'Tier 1: High Priority Buy'
        WHEN SalePrice <= TotalValue AND Bedrooms >= 2 THEN 'Tier 2: Balanced Investment'
        ELSE 'Tier 3: Standard Consideration Market Asset'
    END AS StrategicInvestmentRating
FROM [dbo].[NashvilleHousingEstate]
WHERE TotalValue > 0 AND SalePrice > 0;



