--• Assignment 1: Calculate the exact percentage of missing values (NULLs) for PropertyAddress, OwnerName,
--and TaxDistrict to evaluate overall data completeness.

 SELECT 
COUNT(*) AS TotalRecords,
 SUM(CASE WHEN PropertyAddress IS NULL THEN 1 ELSE 0 END) AS MissingAddressCount,
  CAST(SUM(CASE WHEN PropertyAddress IS NULL THEN 1 ELSE 0 END) * 100.0 / COUNT(*) AS DECIMAL(10,2)) AS MissingAddressPercent,
    
    SUM(CASE WHEN OwnerName IS NULL THEN 1 ELSE 0 END) AS MissingOwnerCount,
   
    SUM(CASE WHEN TaxDistrict IS NULL THEN 1 ELSE 0 END) AS MissingTaxDistrictCount,
    CAST(SUM(CASE WHEN TaxDistrict IS NULL THEN 1 ELSE 0 END) * 100.0 / COUNT(*) AS DECIMAL(10,2)) AS MissingTaxDistrictPercent
FROM [dbo].[NashvilleHousingEstate];


--• Assignment 2: Identify all duplicate records where the same ParcelID, PropertyAddress, SaleDate, 
--and SalePrice appear more than once, and write a query using a CTE and ROW_NUMBER() to isolate them.

 WITH DuplicateCTE AS (
 SELECT *,
       ROW_NUMBER() OVER (
       PARTITION BY ParcelID, PropertyAddress, SaleDate, SalePrice 
            ORDER BY UniqueID
       ) AS RowNum
    FROM dbo.NashvilleHousingEstate
    )
    SELECT * 
FROM DuplicateCTE 
WHERE RowNum > 1;


--• Assignment 3: Write a data verification query to check if there are any mismatching entries where LandValue + BuildingValue 
--does not equal TotalValue.

SELECT 
    UniqueID, ParcelID, LandValue, BuildingValue, TotalValue,
    (LandValue + BuildingValue) AS CalculatedTotal,
    ABS(TotalValue - (LandValue + BuildingValue)) AS DiscrepancyAmount
FROM [dbo].[NashvilleHousingEstate]
