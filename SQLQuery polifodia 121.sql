--• Assignment 14: List the top 3 most common LandUse descriptions in each TaxDistrict using a window partition query.

 WITH RankedLandUse AS (
    SELECT 
        TaxDistrict,
        LandUse,
        COUNT(*) AS UseCount,
        ROW_NUMBER() OVER (PARTITION BY TaxDistrict ORDER BY COUNT(*) DESC) AS RankingOrder
    FROM [dbo].[NashvilleHousingEstate]
    WHERE TaxDistrict IS NOT NULL
    GROUP BY TaxDistrict, LandUse
)
SELECT TaxDistrict, LandUse, UseCount
FROM RankedLandUse
WHERE RankingOrder <= 3;

