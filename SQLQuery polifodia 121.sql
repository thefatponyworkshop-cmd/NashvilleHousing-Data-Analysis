--Phase 2: Macro Market Trends & Seasonality

--How i understand time-series and macroeconomics.
--• Assignment 6: Extract the year from SaleDate and find the total transaction volume (number of sales) 
--and total revenue generated by the Nashville market year-over-year.

SELECT 
    YEAR(SaleDate) AS SaleYear,
    COUNT(*) AS TotalPropertiesSold,
    SUM(CAST(SalePrice AS BIGINT)) AS TotalRevenueGenerated,
    AVG(SalePrice) AS AverageSalePrice
FROM [dbo].[NashvilleHousingEstate]
WHERE SaleDate IS NOT NULL
GROUP BY YEAR(SaleDate)
ORDER BY SaleYear DESC;


--• Assignment 7: Calculate the month-over-month average SalePrice across all years to identify seasonal peaks 
--(e.g., do homes sell for more in the summer?).

  SELECT 
    MONTH(SaleDate) AS SaleMonth,
    DATENAME(MONTH, SaleDate) AS MonthName,
    COUNT(*) AS PropertiesSold,
    AVG(SalePrice) AS AverageSalePrice
FROM [dbo].[NashvilleHousingEstate]
WHERE SaleDate IS NOT NULL
GROUP BY MONTH(SaleDate), DATENAME(MONTH, SaleDate)
ORDER BY SaleMonth ASC;


--• Assignment 8: Rank the top 5 years in Nashville's history that experienced the highest spike in property sales volume using
--a ranking window function (DENSE_RANK()).

 WITH YearlyVolume AS (
    SELECT 
        YEAR(SaleDate) AS SaleYear,
        COUNT(*) AS TotalSales
    FROM [dbo].[NashvilleHousingEstate]
    WHERE SaleDate IS NOT NULL
    GROUP BY YEAR(SaleDate)
)
SELECT 
    SaleYear, 
    TotalSales,
    DENSE_RANK() OVER (ORDER BY TotalSales DESC) AS VolumeRank
FROM YearlyVolume;


